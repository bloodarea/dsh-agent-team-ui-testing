import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';

const source = new URL('../client/', import.meta.url);
const outputDirectory = new URL('../dist/', import.meta.url);
const output = new URL('client.js', outputDirectory);

// DSH loads one classic script. Preserve the factory scope and the panel's hook order.
const sources = [
  'factory/open.jsfrag',
  'shared/view-registry.js',
  'web/audio.js',
  'web/view-channel.js',
  'shared/host.js',
  'shared/view-defaults.js',
  'web/element-references.js',
  'annotations/publisher.js',
  'shared/geometry.js',
  'shared/panel-styles.js',
  'shared/icons.js',
  'web/frame-transport.js',
  'panel/session-binding.js',
  'blender/controls.js',
  'blender/projects.js',
  'blender/references.js',
  'blender/viewport.js',
  'panel/state.jsfrag',
  'panel/target-and-address.js',
  'panel/viewport-sync.js',
  'annotations/workspace.js',
  'annotations/gestures.js',
  'web/pick-element.js',
  'panel/size-and-input.js',
  'web/pointer-input.js',
  'web/frame-lifecycle.js',
  'web/keyboard-input.js',
  'panel/effects.js',
  'panel/actions.js',
  'web/view.js',
  'panel/annotation-view.js',
  'panel/toolbar-and-status.js',
  'blender/view.js',
  'panel/layout.jsfrag',
  'settings/catalog.js',
  'settings/diagnosis.js',
  'settings/host-config.js',
  'settings/pages.js',
  'factory/register.jsfrag',
];

const banner = '// Generated by npm run build:client. Edit the sources in client/.\n';
const parts = await Promise.all(sources.map((name) => readFile(new URL(name, source), 'utf8')));
const bundle = banner + parts.join('');
new Script(bundle, { filename: 'dist/client.js' });

if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8').catch((error) => {
    if (error.code !== 'ENOENT') throw error;
    return null;
  });
  if (existing !== bundle) {
    console.error('dist/client.js is missing or out of date. Run npm run build:client.');
    process.exitCode = 1;
  }
} else {
  await mkdir(outputDirectory, { recursive: true });
  const staging = await mkdtemp(fileURLToPath(new URL('.client-', outputDirectory)));
  const stagedBundle = join(staging, 'client.js');
  try {
    await writeFile(stagedBundle, bundle, 'utf8');
    await rename(stagedBundle, output);
  } finally {
    await rm(staging, { recursive: true, force: true });
  }
}
